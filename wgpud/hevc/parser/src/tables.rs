const fn build_next_state_mps() -> [u8; 128] {
    let mut table: [u8; 128] = [0; 128];
    let mut state: usize = 0;
    while state < 128 {
        let state_index: usize = state >> 1;
        let next_index: usize = if state_index + 1 < 62 { state_index + 1 } else { 62 };
        table[state] = ((next_index << 1) | (state & 1)) as u8;
        state += 1;
    }
    table
}

const fn build_next_state_lps() -> [u8; 128] {
    let mut table: [u8; 128] = [0; 128];
    let mut state: usize = 0;
    while state < 128 {
        let state_index: usize = state >> 1;
        let most_probable: usize = state & 1;
        let next_most_probable: usize = if state_index == 0 { 1 - most_probable } else { most_probable };
        table[state] = (((TRANSITION_LPS[state_index] as usize) << 1) | next_most_probable) as u8;
        state += 1;
    }
    table
}

