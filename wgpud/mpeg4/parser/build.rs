// Generates the record layout and error code constants from the decoder's WGSL, which declares them once for both sides:
// each `const RECORD_<NAME>: u32 = <value>u;` line becomes `<NAME>`, and each `const ERROR_<NAME>: u32 = <value>u;` line keeps its name.
// It also checks that the header's `//! error:` lines name exactly the error codes the WGSL declares; a line's optional third field,
// its recovery, is the engine's and the parser's business alike, so the check reads only the code and the name.

use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::PathBuf;

const DECODER_SOURCE: &str = "../mpeg4.wgsl";
const GENERATED_FILE: &str = "record_layout.rs";
const RECORD_PREFIX: &str = "RECORD_";
const ERROR_PREFIX: &str = "ERROR_";
const ERROR_CODE_SHIFT_NAME: &str = "ERROR_CODE_SHIFT";
const CONSTANT_START: &str = "const ";
const CONSTANT_TYPE: &str = ": u32 = ";
const UNSIGNED_SUFFIX: &str = "u;";
const HEADER_PREFIX: &str = "//!";
const ERROR_DIRECTIVE: &str = "//! error:";
const FIELD_SEPARATOR: char = ',';

/// Returns the name and value of a `const <NAME>: u32 = <value>u;` line, or None for any other line.
fn read_constant(line: &str) -> Option<(String, u32)> {
    let declaration: &str = line.trim().strip_prefix(CONSTANT_START)?;
    let (name, value_text) = declaration.split_once(CONSTANT_TYPE)?;
    let value: u32 = value_text.strip_suffix(UNSIGNED_SUFFIX)?.parse::<u32>().ok()?;
    Some((name.to_string(), value))
}

/// Converts a header error name such as `pictureHeader` to its constant name, `ERROR_PICTURE_HEADER`.
fn to_error_constant_name(name: &str) -> String {
    let mut constant: String = String::from(ERROR_PREFIX);
    for character in name.chars() {
        if character.is_ascii_uppercase() {
            constant.push('_');
        }
        constant.push(character.to_ascii_uppercase());
    }
    constant
}

/// Returns each `//! error: <code>, <name>[, <recovery>]` line's constant name and code.
fn read_error_directives(source: &str) -> BTreeMap<String, u32> {
    let mut directives: BTreeMap<String, u32> = BTreeMap::new();
    for line in source.lines().take_while(|line: &&str| line.starts_with(HEADER_PREFIX)) {
        let Some(value) = line.strip_prefix(ERROR_DIRECTIVE) else {
            continue;
        };
        let mut fields: std::str::Split<'_, char> = value.split(FIELD_SEPARATOR);
        let code_text: &str = fields.next().expect("an error directive holds a code");
        let name: &str = fields.next().expect("an error directive holds a name");
        let code: u32 = code_text.trim().parse::<u32>().expect("an error directive's code is a number");
        directives.insert(to_error_constant_name(name.trim()), code);
    }
    directives
}

fn main() {
    let crate_directory: PathBuf = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is set by cargo"));
    let source_path: PathBuf = crate_directory.join(DECODER_SOURCE);
    let source: String = fs::read_to_string(&source_path).expect("the decoder's WGSL is readable");

    let mut generated: String = String::from("// Generated by build.rs from the RECORD_ and ERROR_ constants of mpeg4.wgsl\n");
    let mut error_constants: BTreeMap<String, u32> = BTreeMap::new();
    for line in source.lines() {
        let Some((name, value)) = read_constant(line) else {
            continue;
        };
        if let Some(record_name) = name.strip_prefix(RECORD_PREFIX) {
            generated.push_str(&format!("pub const {record_name}: u32 = {value};\n"));
        } else if name.starts_with(ERROR_PREFIX) {
            generated.push_str(&format!("pub const {name}: u32 = {value};\n"));
            if name != ERROR_CODE_SHIFT_NAME {
                error_constants.insert(name, value);
            }
        }
    }
    let error_directives: BTreeMap<String, u32> = read_error_directives(&source);
    assert_eq!(error_directives, error_constants, "the //! error lines and the ERROR_ constants of mpeg4.wgsl differ");

    let output_directory: PathBuf = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR is set by cargo"));
    fs::write(output_directory.join(GENERATED_FILE), generated).expect("the generated layout is writable");
    println!("cargo:rerun-if-changed={}", source_path.display());
}
