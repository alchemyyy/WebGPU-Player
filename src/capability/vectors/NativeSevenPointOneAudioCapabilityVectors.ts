function createChunk(base64: string, timestamp: number, duration: number): NativeSurroundAudioCapabilityVectorChunk {
    return {
        data: decodeBase64(base64),
        duration,
        timestamp
    };
}

/** Returns new copies of one codec's encoded 7.1 tone packets and decoder description. */
export function createNativeSevenPointOneAudioCapabilityVector(
    codec: NativeSurroundAudioCapabilityVectorCodec
): NativeSevenPointOneAudioCapabilityVector {
    const common = {
        channelTones: NATIVE_SEVEN_POINT_ONE_AUDIO_CAPABILITY_VECTOR_CHANNEL_TONES,
        codec,
        numberOfChannels: NATIVE_SEVEN_POINT_ONE_AUDIO_CAPABILITY_VECTOR_CHANNEL_COUNT,
        sampleRate: NATIVE_SEVEN_POINT_ONE_AUDIO_CAPABILITY_VECTOR_SAMPLE_RATE
    } as const;
    switch (codec) {
        case 'aac':
            return {
                ...common,
                codecString: 'mp4a.40.2',
                description: decodeBase64(AAC_DESCRIPTION_BASE64),
                encodedChunks: [
                    createChunk(AAC_PACKET_1_BASE64, 0, 21_000),
                    createChunk(AAC_PACKET_2_BASE64, 21_000, 21_000),
                    createChunk(AAC_PACKET_3_BASE64, 42_000, 22_000),
                    createChunk(AAC_PACKET_4_BASE64, 64_000, 21_000),
                    createChunk(AAC_PACKET_5_BASE64, 85_000, 0)
                ]
            };
        case 'opus':
            return {
                ...common,
                codecString: 'opus',
                description: decodeBase64(OPUS_DESCRIPTION_BASE64),
                encodedChunks: [
                    createChunk(OPUS_PACKET_1_BASE64, 0, 21_000),
                    createChunk(OPUS_PACKET_2_BASE64, 21_000, 20_000),
                    createChunk(OPUS_PACKET_3_BASE64, 41_000, 20_000),
                    createChunk(OPUS_PACKET_4_BASE64, 61_000, 11_000)
                ]
            };
        case 'flac':
            return {
                ...common,
                codecString: 'flac',
                description: decodeBase64(FLAC_DESCRIPTION_BASE64),
                encodedChunks: [
                    createChunk(FLAC_PACKET_1_BASE64, 0, 0)
                ]
            };
        case 'vorbis':
            return {
                ...common,
                codecString: 'vorbis',
                description: decodeBase64(VORBIS_DESCRIPTION_BASE64),
                encodedChunks: [
                    createChunk(VORBIS_PACKET_1_BASE64, 0, 3_000),
                    createChunk(VORBIS_PACKET_2_BASE64, 3_000, 3_000),
                    createChunk(VORBIS_PACKET_3_BASE64, 6_000, 12_000),
                    createChunk(VORBIS_PACKET_4_BASE64, 18_000, 21_000),
                    createChunk(VORBIS_PACKET_5_BASE64, 39_000, 21_000),
                    createChunk(VORBIS_PACKET_6_BASE64, 60_000, 0)
                ]
            };
    }
}
